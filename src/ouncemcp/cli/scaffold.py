"""``ouncemcp init``: scaffold a working server with tests and CI (spec DX-1).

The scaffold has one read tool and one write tool, tests that call both and check the
token budget, and a GitHub Actions workflow that runs the tests and ``ouncemcp check``.
It passes its own tests as generated; ``tests/test_dx1_dx2_init_dev.py`` runs them.
"""

from __future__ import annotations

import keyword
import re
from pathlib import Path

from ouncemcp import __version__

_SERVER = '''"""{title}: an MCP server built with OunceMCP.

Run over stdio:     python server.py
Develop:            ouncemcp dev server.py
Check budgets:      ouncemcp check server.py
"""

from __future__ import annotations

from typing import Annotated

from pydantic import BaseModel, Field

from ouncemcp import Cursor, Detail, Effect, InvalidInput, OunceServer, Paginated, ToolContext

server = OunceServer(
    "{name}",
    instructions="Notes. Search first, then add a note if nothing matches.",
)

NOTES: dict[str, dict[str, str]] = {{
    "n-1": {{"title": "Welcome", "body": "This server was generated by ouncemcp init."}},
}}


class Note(BaseModel):
    id: str
    title: str
    body: Annotated[str | None, Detail] = None  # only with response_format=detailed


class SearchResult(BaseModel):
    items: Annotated[list[Note], Paginated]
    next_cursor: Cursor = None


class SearchInput(BaseModel):
    query: str = Field("", description="Words to look for in titles; empty lists all")
    limit: int = Field(20, ge=1, le=50)
    cursor: str | None = Field(None, description="next_cursor from the previous call")


@server.tool(name="notes.search", effect=Effect.READ)
async def search(args: SearchInput, ctx: ToolContext) -> SearchResult:
    """Find notes by words in their title. Use notes.add to create one."""
    words = args.query.lower().split()
    rows = [
        Note(id=note_id, title=note["title"], body=note["body"])
        for note_id, note in sorted(NOTES.items())
        if all(word in note["title"].lower() for word in words)
    ]
    page = ctx.page(rows, cursor=args.cursor, limit=args.limit)
    return SearchResult(items=page.items, next_cursor=page.next_cursor)


class AddInput(BaseModel):
    title: str = Field(min_length=1, max_length=120)
    body: str = Field("", max_length=4000)


class Added(BaseModel):
    id: str
    title: str


@server.tool(name="notes.add", effect=Effect.WRITE)
async def add(args: AddInput) -> Added:
    """Add a note. Side effect: stores the note. Search first to avoid duplicates."""
    if any(note["title"] == args.title for note in NOTES.values()):
        raise InvalidInput(
            "A note with this title already exists.", hint="Search for it with notes.search."
        )
    note_id = f"n-{{len(NOTES) + 1}}"
    NOTES[note_id] = {{"title": args.title, "body": args.body}}
    return Added(id=note_id, title=args.title)


if __name__ == "__main__":
    server.run()
'''

