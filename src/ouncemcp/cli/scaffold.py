_GITIGNORE = """__pycache__/
.venv/
.pytest_cache/
*.egg-info/
"""


class ScaffoldError(Exception):
    pass


def _names(raw: str) -> tuple[str, str, str]:
    """(server name, distribution name, title) from what the user typed."""
    base = Path(raw).name
    slug = re.sub(r"[^A-Za-z0-9]+", "-", base).strip("-").lower()
    if not slug or not slug[0].isalpha():
        raise ScaffoldError(
            f"'{raw}' is not a usable name: start with a letter, e.g. ouncemcp init notes-server"
        )
    if keyword.iskeyword(slug.replace("-", "_")):
        raise ScaffoldError(f"'{raw}' is a Python keyword; choose another name")
    title = " ".join(part.capitalize() for part in slug.split("-"))
    return slug, slug, title


def scaffold(target: str | Path, *, force: bool = False) -> list[Path]:
    """Write the scaffold into directory ``target`` and return the files written."""
    root = Path(target)
    name, dist, title = _names(str(target))
    if root.exists() and any(root.iterdir()) and not force:
        raise ScaffoldError(f"{root} is not empty; choose a new directory or pass --force")
    pin = "" if "dev" in __version__ else f">={__version__}"
    files = {
        "server.py": _SERVER.format(name=name, title=title),
        "tests/test_server.py": _TESTS.format(name=name),
        "pyproject.toml": _PYPROJECT.format(dist=dist, title=title, pin=pin),
        ".github/workflows/ci.yml": _CI,
        "README.md": _README.format(title=title),
        ".gitignore": _GITIGNORE,
    }
    written = []
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written
